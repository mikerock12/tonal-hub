"""Train and quantize TonalMuse Tiny v1; standard library only; all examples are original synthetic text.

This is a small multilabel linear text model, not a conversational LLM. Template
families are held out. Reported validation measures this synthetic corpus only.
"""
from pathlib import Path
import collections,hashlib,json,math,random,re,time,unicodedata

ROOT=Path(__file__).resolve().parents[1]
D=4096
def normalize(text):
    return re.sub(r'[^\w]+',' ',''.join(c for c in unicodedata.normalize('NFD',text.lower()) if not unicodedata.combining(c)),flags=re.UNICODE).strip()
def hashed(text):
    h=2166136261
    for b in text.encode('utf-8'):h=((h^b)*16777619)&0xffffffff
    return h%D
def features(text):
    words=normalize(text[:12000]).split()[:1200];out=set();previous='';neg=0
    for word in words:
        if word in ('not','never','without','nao','nunca','sem','sin','no'):neg=3
        prefix='n:' if neg else 'w:'
        out.add(hashed(prefix+word))
        if previous:out.add(hashed('b:'+previous+' '+word))
        if len(word)>=5:
            for i in range(len(word)-3):out.add(hashed(prefix+'#'+word[i:i+4]))
        previous=word;neg=max(0,neg-1)
        if len(out)>=768:break
    return sorted(out)
def sigmoid(x):return 1/(1+math.exp(-max(-20,min(20,x))))
def main():
    start=time.perf_counter();rng=random.Random(717);data=json.loads((ROOT/'resources/muse-training.json').read_text(encoding='utf-8'));labels=list(data['labels']);k=len(labels)
    train_templates=['{a}','{a}. {b}','The verse describes {a} and {b}','A song about {a}','A letra fala de {a} e {b}','Nesta canção há {a}','El verso habla de {a} y {b}','A narrativa musical sugere {a}']
    heldout_templates=['This musical story expresses {a}; also {b}','O tema central desta letra envolve {a}, acompanhado de {b}','Esta narración cantada trata de {a} y {b}']
    def examples(templates,n):
        examples=[]
        for label,phrases in data['labels'].items():
            for _ in range(n):
                a,b=rng.sample(phrases,2);target=[0.]*k;target[labels.index(label)]=1
                examples.append((features(rng.choice(templates).format(a=a,b=b)),target))
        for text in data['neutral']*max(1,n//4):examples.append((features(text),[0.]*k))
        return examples
    train=examples(train_templates,180);validation=examples(heldout_templates,60)
    # Mixtures train independent labels rather than forcing one theme per song.
    for _ in range(400):
        a,b=rng.sample(labels,2);text=rng.choice(data['labels'][a])+'. '+rng.choice(data['labels'][b]);target=[float(x in (a,b)) for x in labels];train.append((features(text),target))
    weights=[[0.]*D for _ in labels];bias=[-1.5]*k
    for epoch in range(12):
        rng.shuffle(train);rate=.12/(1+epoch*.12)
        for fs,target in train:
            scale=1/math.sqrt(max(1,len(fs)))
            for j in range(k):
                row=weights[j];p=sigmoid(bias[j]+sum(row[i] for i in fs)*scale);delta=(target[j]-p)*rate*(3 if target[j] else 1)
                bias[j]+=delta*.1
                for i in fs:row[i]=row[i]*.99999+delta*scale
    scales=[max(max(abs(v) for v in row)/127,1e-8) for row in weights];quant=[[max(-127,min(127,round(v/scales[j]))) for v in row] for j,row in enumerate(weights)]
    def predict(fs):
        scale=1/math.sqrt(max(1,len(fs)));return [sigmoid(bias[j]+sum(quant[j][i]*scales[j] for i in fs)*scale) for j in range(k)]
    tp=fp=fn=exact=0
    for fs,target in validation:
        got=[p>=.60 for p in predict(fs)];truth=[v>0 for v in target];exact+=got==truth
        for a,b in zip(got,truth):tp+=a and b;fp+=a and not b;fn+=b and not a
    model=ROOT/'src/insights/MuseWeights.inc';model.parent.mkdir(parents=True,exist_ok=True)
    lines=['// Generated by training/train_muse.py from original MIT synthetic data. Do not edit.','static constexpr int kDimensions=4096;','static constexpr std::array<const char*,8> kLabels={'+','.join(json.dumps(x) for x in labels)+'};','static constexpr std::array<float,8> kBias={'+','.join(f'{x:.9g}f' for x in bias)+'};','static constexpr std::array<float,8> kScales={'+','.join(f'{x:.9g}f' for x in scales)+'};','static constexpr std::array<std::array<int8_t,4096>,8> kWeights={{']
    for row in quant:
        lines.append('{{');lines.extend(','.join(map(str,row[i:i+64]))+',' for i in range(0,D,64));lines.append('}},')
    lines.append('}};');model.write_text('\n'.join(lines)+'\n',encoding='utf-8')
    report={'name':'TonalMuse Tiny v1','kind':'multilabel hashed linear text classifier; not a conversational LLM','license':'MIT','seed':717,'labels':labels,'dimensions':D,'quantization':'int8 with per-label scale','weight_payload_bytes':k*D+k*4*2,'training_examples':len(train),'validation_examples':len(validation),'split':'held-out template families; vocabulary shared; synthetic internal validation only','validation_exact_match':exact/len(validation),'validation_micro_f1':2*tp/max(1,2*tp+fp+fn),'threshold':.60,'training_seconds':time.perf_counter()-start,'data_sha256':hashlib.sha256((ROOT/'resources/muse-training.json').read_bytes()).hexdigest(),'generated_sha256':hashlib.sha256(model.read_bytes()).hexdigest(),'limits':['No real-song external accuracy claim','Cannot infer the listener mental state','Irony, negation scope and languages outside PT/EN/ES may be misclassified','Genres and listening totals come from metadata and actual logs, not predictions']}
    (ROOT/'docs/muse-training-v1.json').write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n',encoding='utf-8');print(json.dumps(report,ensure_ascii=False,indent=2))
if __name__=='__main__':main()
